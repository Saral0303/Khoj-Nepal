function getLang() {
  return localStorage.getItem('khoj_lang') || 'en';
}

function setLang(lang) {
  localStorage.setItem('khoj_lang', lang);
  document.documentElement.lang = lang === 'ne' ? 'ne' : 'en';
  document.documentElement.setAttribute('data-lang', lang);
  applyTranslations();
  window.dispatchEvent(new CustomEvent('khoj:langchange', { detail: { lang } }));
}

function t(key, vars) {
  const lang = getLang();
  let text = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return text;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      /* ignore — use placeholder attr */
    } else {
      el.textContent = text;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  document.documentElement.lang = getLang() === 'ne' ? 'ne' : 'en';
}
